// Converts Supabase Table Editor CSV exports in seed/csv/ into seed/data.sql for D1.
//
// Usage (from worker/):  node scripts/csv-to-seed.mjs
// Expects playlists_rows.csv, videos_rows.csv and attachments_rows.csv.

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const seedDir = fileURLToPath(new URL('../seed/', import.meta.url))

const tables = [
  { name: 'playlists', columns: ['id', 'title', 'description', 'image_url', 'sort_order', 'is_active', 'created_at'] },
  { name: 'videos', columns: ['id', 'playlist_id', 'title', 'description', 'drive_file_id', 'video_url', 'video_source', 'sort_order', 'is_active', 'is_quiz', 'created_at'] },
  { name: 'attachments', columns: ['id', 'video_id', 'title', 'description', 'url', 'file_type', 'sort_order', 'is_active', 'created_at'] },
]
const integerColumns = new Set(['sort_order'])
const booleanColumns = new Set(['is_active', 'is_quiz'])

// RFC 4180 parser: handles quoted fields, escaped quotes and newlines inside quotes.
function parseCsv(text) {
  const rows = []
  let row = []
  let field = ''
  let quoted = false
  text = text.replace(/^﻿/, '')

  for (let i = 0; i < text.length; i++) {
    const char = text[i]
    if (quoted) {
      if (char === '"' && text[i + 1] === '"') { field += '"'; i++ }
      else if (char === '"') quoted = false
      else field += char
    } else if (char === '"') quoted = true
    else if (char === ',') { row.push(field); field = '' }
    else if (char === '\n' || char === '\r') {
      if (char === '\r' && text[i + 1] === '\n') i++
      row.push(field); rows.push(row); row = []; field = ''
    } else field += char
  }
  if (field || row.length) { row.push(field); rows.push(row) }

  const [header, ...body] = rows.filter((r) => r.some((value) => value !== ''))
  return body.map((values) => Object.fromEntries(header.map((key, index) => [key, values[index] ?? ''])))
}

// "2026-09-21 09:12:19.227497+00" -> "2026-09-21T09:12:19.227Z"
function toIsoTimestamp(value) {
  const date = new Date(value.replace(' ', 'T').replace(/(\.\d{3})\d*/, '$1').replace(/([+-]\d{2})$/, '$1:00'))
  if (Number.isNaN(date.getTime())) throw new Error(`Invalid timestamp: ${value}`)
  return date.toISOString()
}

function sqlValue(column, raw) {
  if (raw === '') return 'NULL'
  if (booleanColumns.has(column)) {
    if (!['true', 'false'].includes(raw)) throw new Error(`Invalid boolean for ${column}: ${raw}`)
    return raw === 'true' ? '1' : '0'
  }
  if (integerColumns.has(column)) {
    if (!/^\d+$/.test(raw)) throw new Error(`Invalid integer for ${column}: ${raw}`)
    return raw
  }
  if (column === 'created_at') return `'${toIsoTimestamp(raw)}'`
  return `'${raw.replace(/'/g, "''")}'`
}

const lines = [
  '-- Generated by scripts/csv-to-seed.mjs from seed/csv/. Replaces all content in D1.',
  'DELETE FROM attachments;',
  'DELETE FROM videos;',
  'DELETE FROM playlists;',
]

for (const table of tables) {
  const rows = parseCsv(readFileSync(`${seedDir}csv/${table.name}_rows.csv`, 'utf8'))
  for (const row of rows) {
    const record = { ...row, is_quiz: row.isQuiz ?? row.is_quiz ?? 'false' }
    const values = table.columns.map((column) => sqlValue(column, record[column] ?? ''))
    lines.push(`INSERT INTO ${table.name} (${table.columns.join(', ')}) VALUES (${values.join(', ')});`)
  }
  const inactive = rows.filter((row) => row.is_active === 'false').length
  console.log(`${table.name}: ${rows.length} rows (${inactive} inactive)`)
}

writeFileSync(`${seedDir}data.sql`, lines.join('\n') + '\n')
console.log(`Wrote ${seedDir}data.sql`)
