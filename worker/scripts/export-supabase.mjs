// One-off migration: reads playlists, videos and attachments from Supabase
// and writes them as SQLite INSERT statements to seed/data.sql for D1.
//
// Usage (from worker/):  node scripts/export-supabase.mjs [path/to/.env]
// Reads VITE_SUPABASE_URL and VITE_SUPABASE_ANON_KEY (or SUPABASE_URL / SUPABASE_KEY).
// With the anon key RLS only returns active rows; pass a service_role key as
// SUPABASE_KEY to export inactive rows too.

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const envPath = process.argv[2] ?? fileURLToPath(new URL('../../.env', import.meta.url))
const fileEnv = Object.fromEntries(
  readFileSync(envPath, 'utf8')
    .split(/\r?\n/)
    .map((line) => line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/))
    .filter(Boolean)
    .map(([, key, value]) => [key, value.replace(/^["']|["']$/g, '')]),
)
const env = { ...fileEnv, ...process.env }
const url = env.SUPABASE_URL ?? env.VITE_SUPABASE_URL
const key = env.SUPABASE_KEY ?? env.VITE_SUPABASE_ANON_KEY
if (!url || !key) throw new Error('Missing Supabase URL or key')

const tables = [
  { name: 'playlists', columns: ['id', 'title', 'description', 'image_url', 'sort_order', 'is_active', 'created_at'] },
  { name: 'videos', columns: ['id', 'playlist_id', 'title', 'description', 'drive_file_id', 'video_url', 'video_source', 'sort_order', 'is_active', 'is_quiz', 'created_at'] },
  { name: 'attachments', columns: ['id', 'video_id', 'title', 'description', 'url', 'file_type', 'sort_order', 'is_active', 'created_at'] },
]

function sqlValue(value) {
  if (value === null || value === undefined) return 'NULL'
  if (typeof value === 'boolean') return value ? '1' : '0'
  if (typeof value === 'number') return String(value)
  return `'${String(value).replace(/'/g, "''")}'`
}

const lines = [
  '-- Generated by scripts/export-supabase.mjs. Replaces all content in D1.',
  'DELETE FROM attachments;',
  'DELETE FROM videos;',
  'DELETE FROM playlists;',
]

for (const table of tables) {
  const response = await fetch(`${url}/rest/v1/${table.name}?select=*&order=created_at`, {
    headers: { apikey: key, Authorization: `Bearer ${key}` },
  })
  if (!response.ok) throw new Error(`${table.name}: ${response.status} ${await response.text()}`)
  const rows = await response.json()

  for (const row of rows) {
    const record = { ...row, is_quiz: row.isQuiz, created_at: row.created_at && new Date(row.created_at).toISOString() }
    const values = table.columns.map((column) => sqlValue(record[column]))
    lines.push(`INSERT INTO ${table.name} (${table.columns.join(', ')}) VALUES (${values.join(', ')});`)
  }
  console.log(`${table.name}: ${rows.length} rows`)
}

const outPath = fileURLToPath(new URL('../seed/data.sql', import.meta.url))
writeFileSync(outPath, lines.join('\n') + '\n')
console.log(`Wrote ${outPath}`)
